// OFFLINE SWEEP — generates the LJ_PRETUNE table for lennard-jones.cu
// =============================================================================
// Call once, capture stdout, paste the printed block into lennard-jones.cu.
// Example: ./lj.out --sweep  (wire up in main.c as desired)
void tune_sweep_and_print(unsigned int n_min, unsigned int n_max, unsigned int n_step,
                           double density, double temperature, unsigned int seed) {
    const unsigned int count = (n_max - n_min) / n_step + 1;
    printf("// Auto-generated by tune_sweep_and_print\n");
    printf("// density=%.4f  temperature=%.4f  seed=%u\n", density, temperature, seed);
    printf("#define LJ_PRETUNE_COUNT %u\n", count);
    printf("static const struct { unsigned int n; float skin_frac; unsigned int block; } "
           "LJ_PRETUNE[] = {\n");

    for (unsigned int n = n_min; n <= n_max; n += n_step) {
        // In tune_sweep_and_print, before each tune_skin_3d call:
        g_skin            = 0.3 * R_CUT;
        g_block_size      = 128;
        g_max_neighbours  = 0;
        g_n_cells_side    = 0;
        g_n_cells         = 0;
        g_rebuild_counter = 0;
        d_n               = 0;

        #define SAFE_FREE(ptr) \
        if (ptr) { \
            cudaError_t _e = cudaFree(ptr); \
            if (_e != cudaSuccess) \
                fprintf(stderr, "[RESET] cudaFree(" #ptr ") failed: %s\n", \
                        cudaGetErrorString(_e)); \
            ptr = nullptr; \
        }
        #define SAFE_FREE_HOST(ptr) \
            if (ptr) { \
                cudaError_t _e = cudaFreeHost(ptr); \
                if (_e != cudaSuccess) \
                    fprintf(stderr, "[RESET] cudaFreeHost(" #ptr ") failed: %s\n", \
                            cudaGetErrorString(_e)); \
                ptr = nullptr; \
            }

        SAFE_FREE(d_x);   SAFE_FREE(d_y);   SAFE_FREE(d_z);
        SAFE_FREE(d_vx);  SAFE_FREE(d_vy);  SAFE_FREE(d_vz);
        SAFE_FREE(d_fx);  SAFE_FREE(d_fy);  SAFE_FREE(d_fz);
        SAFE_FREE(d_pe_arr);   SAFE_FREE(d_pe_total);
        SAFE_FREE(d_x_ref);    SAFE_FREE(d_y_ref);   SAFE_FREE(d_z_ref);
        SAFE_FREE(d_xs);  SAFE_FREE(d_ys);  SAFE_FREE(d_zs);
        SAFE_FREE(d_vxs); SAFE_FREE(d_vys); SAFE_FREE(d_vzs);
        SAFE_FREE(d_nl_count); SAFE_FREE(d_nl);
        SAFE_FREE(d_flag);     SAFE_FREE(d_overflow);
        SAFE_FREE(d_cell_id);  SAFE_FREE(d_cell_start);
        SAFE_FREE(d_cell_count); SAFE_FREE(d_cell_part);
        SAFE_FREE_HOST(h_flag_pinned);

        #undef SAFE_FREE
        #undef SAFE_FREE_HOST
        
        const double particle_box_size = ceil(cbrt((double)n / density));
        const double box_size          = (4.0 / 3.0) * particle_box_size;
        const double box_fraction      = particle_box_size / box_size;
        
        Particle *particles = (Particle*)calloc(n, sizeof(Particle));
        if (!particles) { fprintf(stderr, "[SWEEP] OOM at N=%u\n", n); break; }

        initialize_particles(particles, n, box_size, box_fraction, seed, temperature);

        fprintf(stderr, "[SWEEP] N=%u  box=%.2f ...\n", n, box_size);
        fprintf(stdout, "[DEBUG] n=%u  particle_box=%.10f  box_size=%.10f  density=%.10f\n",
        n, particle_box_size, box_size, (double)n/(box_size*box_size*box_size));
        TuneResult r = tune_skin_3d(particles, n, box_size);

        printf("    { %6u, %.2ff, %3u },  // %.3f ms/step\n",
               n, (float)(r.skin / R_CUT), r.block_size, r.ms_per_step);
        fflush(stdout);
        free(particles);
    }

    printf("};\n");
}
