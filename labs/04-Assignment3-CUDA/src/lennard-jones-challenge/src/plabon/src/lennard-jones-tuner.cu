    fprintf(stdout, "[CELL] %u cells/side  %u total cells\n", g_n_cells_side, g_n_cells);

    const size_t sz = (size_t)n * sizeof(double);
    CUDA_CHECK(cudaMalloc(&d_x,  sz)); CUDA_CHECK(cudaMalloc(&d_y,  sz)); CUDA_CHECK(cudaMalloc(&d_z,  sz));
